#!/usr/bin/env python3
"""Static source-contract checks for the app-owned Harmony text-input host.

This reads source and generated output only. It is not an ArkTS parser, compiler,
IME simulator or native runtime test. Run test_harmony_text_input.py for negative
fixtures and use the authorized toolchain for actual compilation and execution.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys
from typing import Sequence

ROOT = Path(__file__).resolve().parents[1]
HOST = Path("examples/harmony/entry/src/main/ets/native/NativeTextInputHost.ets")
CANONICAL_HOST = Path("Fixtures/interop-text-input-host/NativeTextInputHost.ets")
GENERATED = Path("examples/harmony/entry/src/main/ets/generated/InteropTextInputHost.ets")
PARENT = Path("examples/harmony/entry/src/ohosTest/ets/testability/GeneratedComposerHost.ets")
NATIVE_TEST = Path("examples/harmony/entry/src/ohosTest/ets/test/GeneratedComposer.test.ets")
REQUIRED_PATHS = (
    CANONICAL_HOST,
    HOST,
    GENERATED,
    PARENT,
    NATIVE_TEST,
    Path("Fixtures/interop-text-input-host/Input.swift"),
    Path("Fixtures/interop-text-input-host/Expected.ets"),
    Path("examples/shared/InteropTextInputHost.swift"),
    Path("examples/harmony/entry/src/ohosTest/ets/testability/ComposerDraftModel.ets"),
    Path("examples/harmony/entry/src/ohosTest/ets/testability/ComposerTestAbility.ets"),
    Path("examples/harmony/entry/src/ohosTest/module.json5"),
    Path("examples/harmony/entry/src/ohosTest/resources/base/profile/test_pages.json"),
)


class SourceContractError(ValueError):
    """A required source boundary or explicit diagnostic is missing."""


def require(condition: bool, message: str) -> None:
    if not condition:
        raise SourceContractError(message)


def body(source: str, signature: str) -> str:
    """Extract one brace-delimited method, after locating its exact signature."""
    start = source.find(signature)
    require(start >= 0, f"missing native method: {signature}")
    opening = source.find("{", start + len(signature))
    require(opening >= 0, f"missing body: {signature}")
    depth = 0
    for index in range(opening, len(source)):
        if source[index] == "{":
            depth += 1
        elif source[index] == "}":
            depth -= 1
            if depth == 0:
                return source[opening + 1:index]
    raise SourceContractError(f"unterminated native method: {signature}")


def ordered(source: str, calls: Sequence[str]) -> None:
    positions = [source.find(call) for call in calls]
    require(all(position >= 0 for position in positions), f"missing required calls in order: {calls}")
    require(positions == sorted(positions), f"required calls are out of order: {calls}")


def strip_comments(source: str) -> str:
    source = re.sub(r"/\*.*?\*/", "", source, flags=re.DOTALL)
    return re.sub(r"//[^\n]*", "", source)


def validate_source_contract(root: Path = ROOT) -> None:
    missing = [str(path) for path in REQUIRED_PATHS if not (root / path).is_file()]
    require(not missing, f"missing host sources: {missing}")
    host = (root / HOST).read_text(encoding="utf-8")
    canonical = (root / CANONICAL_HOST).read_text(encoding="utf-8")
    generated = (root / GENERATED).read_text(encoding="utf-8").replace(
        "// Source: InteropTextInputHost.swift\n", "// Source: Input.swift\n", 1,
    )
    parent = (root / PARENT).read_text(encoding="utf-8")
    native_test = (root / NATIVE_TEST).read_text(encoding="utf-8")
    executable = strip_comments(host)

    require(host == canonical, f"{HOST} must remain byte-identical to {CANONICAL_HOST}")
    require(
        (root / "examples/shared/InteropTextInputHost.swift").read_bytes()
        == (root / "Fixtures/interop-text-input-host/Input.swift").read_bytes(),
        "the generated example must use the canonical shared host ABI",
    )
    require(
        generated == (root / "Fixtures/interop-text-input-host/Expected.ets").read_text(encoding="utf-8"),
        "the example composer must remain actual canonical generated output",
    )
    require(generated.startswith("// Generated by Refract; DO NOT EDIT."), "generated header is missing")
    require("TextInput({" not in generated, "an ordinary TextInput cannot replace the typed native host")
    for argument in (
        "draft: this.draft,", "focusRequest: this.focusRequest,",
        "onDraftCommit: (value: string): void => { this.model.commitDraft(value); },",
        "onCommit: (): void => { this.model.commit(); },",
    ):
        require(argument in generated, f"generated host ABI changed: {argument}")

    for declaration in (
        "@Require @Param draft: string;",
        "@Event onDraftChange: (value: string) => void = (value: string): void => {};",
        "@Require @Param focusRequest: number;",
        "@Event onDraftCommit: (value: string) => void = (value: string): void => {};",
        "@Event onCommit: () => void = (): void => {};",
        "private previewActive: boolean = false;",
    ):
        require(declaration in executable, f"missing bounded native declaration: {declaration}")
    require("enablePreviewText(true)" in executable, "native IME preview must remain enabled")
    require("enterKeyType(EnterKeyType.Done)" in executable, "the native Done key is required")
    for unsupported in ("clearPreviewText(", "setComposingText(", "commitText(", "addText("):
        require(unsupported not in executable, f"the host must not synthesize editing: {unsupported}")
    require(
        re.search(r"(?:draft|editorDraft)\s*=\s*previewText", executable) is None,
        "preview text must never enter either committed-draft value",
    )

    editing = body(executable, "private nativeEditChanged(")
    ordered(editing, (
        "previewText !== undefined && previewText.value.length > 0",
        "if (this.previewActive)", "return;", "this.editorDraft = value;",
        "this.onDraftChange(value);",
    ))
    require(
        re.search(r"(?:draft|editorDraft|onDraftChange|onDraftCommit)\([^)]*previewText", editing) is None,
        "preview must be isolated before any committed-draft publication",
    )
    external = body(executable, "applyExternalDraft(")
    require("if (!this.previewActive)" in external, "external drafts must not replace active native preview")
    require("this.editorDraft = this.draft;" in external, "committed external edits must reach the editor")

    submit = body(executable, "private finishNativeSubmit(")
    ordered(submit, (
        "if (this.previewActive)", "event.keepEditableState();", "return;",
        "this.controller.stopEditing();", "const committed: string = event.text;",
        "this.editorDraft = committed;", "this.onDraftCommit(committed);",
        "this.onDraftChange(committed);", "getFocusController().clearFocus();", "this.onCommit();",
    ))
    require("if (this.draft !== committed)" not in submit, "ongoing committed-draft publication must not depend on a stale parent binding")
    require("previewActive = false" not in submit, "Done must not pretend preview was committed")
    require("select an IME candidate before Done" in host, "unsupported active-preview submit needs a visible diagnostic")
    require("Text(this.diagnostic)" in executable, "the native diagnostic must be visible")

    focus = body(executable, "requestNativeFocus(")
    ordered(focus, (
        "if (this.focusRequest <= this.lastFocusRequest)",
        "this.lastFocusRequest = this.focusRequest;",
        "getFocusController().requestFocus('refract_native_text_input')",
        "inputMethod.getController().showTextInput((error: BusinessError)",
        "native keyboard request failed", "console.error(this.diagnostic)",
        "catch (error)", "native focus request failed",
    ))
    require(".id('refract_native_text_input')" in executable, "native focus must target the editor")

    require("ComposerScreen({" in parent, "the native parent must invoke the real generated composer")
    require("@Local private draft: string = 'Retained draft';" in parent, "the parent must retain its draft")
    require("this.draft = value;" in parent, "the parent must own ongoing committed-draft updates")
    require("this.focusRequest += 1;" in parent, "focus restoration must issue a new token")
    require("if (this.showComposer)" in parent, "recreation must exercise the actual generated child")
    require("@Trace lastSubmittedDraft: string" in (root / "examples/harmony/entry/src/ohosTest/ets/testability/ComposerDraftModel.ets").read_text(encoding="utf-8"), "submitted drafts must be retained by the application model")

    ability = (root / "examples/harmony/entry/src/ohosTest/ets/testability/ComposerTestAbility.ets").read_text(encoding="utf-8")
    require("generatedComposerTests();" in ability, "the separate native test ability must register its checks")
    require("testability/GeneratedComposerHost" in ability, "the native test must load the actual generated host")
    module = (root / "examples/harmony/entry/src/ohosTest/module.json5").read_text(encoding="utf-8")
    require("ComposerTestAbility.ets" in module, "the separate composer ability must be registered")
    pages = json.loads((root / "examples/harmony/entry/src/ohosTest/resources/base/profile/test_pages.json").read_text(encoding="utf-8"))
    require("testability/GeneratedComposerHost" in pages["src"], "the composer host page must be registered")

    test_code = strip_comments(native_test)
    require("inputText('Native committed edit')" in test_code, "native committed-edit scaffold is missing")
    require("KeyCode.KEYCODE_ENTER" in test_code, "native hardware Enter scaffold is missing")
    require("native_restore_composer" in test_code, "native recreation/draft-retention scaffold is missing")
    require("inputText('ni')" not in test_code, "text injection must not masquerade as IME preedit")
    for forbidden in ("setComposingText", "previewText", "commitText("):
        require(forbidden not in test_code, f"native UI Test cannot synthesize IME operations: {forbidden}")


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT, help="repository root containing the checked-in sources")
    arguments = parser.parse_args(argv)
    try:
        validate_source_contract(arguments.root.resolve())
    except (OSError, SourceContractError, json.JSONDecodeError) as error:
        print(f"harmony-text-input-static: {error}", file=sys.stderr)
        return 1
    print("Harmony text-input source contracts pass; no ArkTS compilation or IME execution was performed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
