package com.example.refract.chat

import androidx.compose.runtime.State
import androidx.compose.runtime.mutableStateOf
import refract.generated.ChatBlock
import refract.generated.ChatMessage
import refract.generated.ConversationModel

/** One whole-message mutation. The application owns transport ordering and calls this serially. */
internal sealed interface MessageMutation {
    val messageID: String
    val revision: Long
}

internal data class AppendBlocks(
    override val messageID: String,
    override val revision: Long,
    val blocks: List<ChatBlock>,
) : MessageMutation

internal data class UpdateBlock(
    override val messageID: String,
    override val revision: Long,
    val block: ChatBlock,
) : MessageMutation

internal data class FinalizeMessage(
    override val messageID: String,
    override val revision: Long,
) : MessageMutation

/** Validation errors are explicit and leave the last published immutable snapshot untouched. */
internal enum class ProjectionRejection {
    MISSING_MESSAGE,
    INVALID_IDENTITY,
    DUPLICATE_IDENTITY,
    BLOCK_OWNERSHIP,
    REVISION_RANGE,
    STALE_REVISION,
    CONFLICTING_REVISION,
    DUPLICATE_APPEND,
    DUPLICATE_FINALIZE,
    ALREADY_FINAL,
    CAPACITY,
}

internal class ProjectionException(val reason: ProjectionRejection) : IllegalArgumentException(reason.name)

/**
 * Native reference projection, deliberately not generated by Refract.
 * All new message/block ids and all revisions are validated before publishing one new list.
 */
internal class MessageProjection(
    messageCapacity: Int,
    blockCapacity: Int,
) : ConversationModel {
    init {
        require(messageCapacity >= 0 && blockCapacity >= 0) { "Capacities must be nonnegative" }
    }

    private val messageCapacity = messageCapacity
    private val blockCapacity = blockCapacity
    private val mutableMessages = mutableStateOf<List<ChatMessage>>(emptyList())
    override val messages: State<List<ChatMessage>> get() = mutableMessages

    // A block permanently belongs to its first message, including after its content is replaced.
    private val blockOwners = mutableMapOf<String, String>()

    // Only the complete last accepted operation can replay at the published revision.
    // Block suffixes or equal content elsewhere in the snapshot are not operation identity.
    private val lastMutations = mutableMapOf<String, MessageMutation>()

    val snapshot: List<ChatMessage> get() = messages.value

    fun create(messageID: String, revision: Long, blocks: List<ChatBlock> = emptyList()) {
        if (messageID.isEmpty()) throw ProjectionException(ProjectionRejection.INVALID_IDENTITY)
        if (snapshot.any { it.id == messageID }) {
            throw ProjectionException(ProjectionRejection.DUPLICATE_IDENTITY)
        }
        if (snapshot.size == messageCapacity) throw ProjectionException(ProjectionRejection.CAPACITY)
        val message = message(messageID, revision, blocks, finalized = false)
        val next = snapshot + message
        validateBlockOwners(next)
        blockOwners.putAll(next.flatMap { item -> item.blocks.map { it.id to item.id } })
        mutableMessages.value = next
    }

    fun append(messageID: String, revision: Long, blocks: List<ChatBlock>) {
        apply(AppendBlocks(messageID, revision, blocks))
    }

    fun update(messageID: String, revision: Long, block: ChatBlock) {
        apply(UpdateBlock(messageID, revision, block))
    }

    fun finalize(messageID: String, revision: Long) {
        apply(FinalizeMessage(messageID, revision))
    }

    fun apply(mutation: MessageMutation) {
        val current = snapshot.firstOrNull { it.id == mutation.messageID }
            ?: throw ProjectionException(ProjectionRejection.MISSING_MESSAGE)
        if (mutation.revision < current.revision) {
            throw ProjectionException(ProjectionRejection.STALE_REVISION)
        }
        if (mutation.revision == current.revision) {
            if (lastMutations[mutation.messageID] == mutation) return
            throw ProjectionException(ProjectionRejection.CONFLICTING_REVISION)
        }
        if (current.finalized) {
            if (mutation is FinalizeMessage) {
                throw ProjectionException(ProjectionRejection.CONFLICTING_REVISION)
            }
            throw ProjectionException(ProjectionRejection.ALREADY_FINAL)
        }
        val updated = when (mutation) {
            is AppendBlocks -> {
                if (mutation.blocks.isEmpty()) throw ProjectionException(ProjectionRejection.DUPLICATE_APPEND)
                if (mutation.blocks.any { block -> current.blocks.any { it.id == block.id } }) {
                    throw ProjectionException(ProjectionRejection.DUPLICATE_APPEND)
                }
                current.copy(revision = mutation.revision, blocks = current.blocks + mutation.blocks)
            }
            is UpdateBlock -> {
                if (current.blocks.none { it.id == mutation.block.id }) {
                    throw ProjectionException(ProjectionRejection.BLOCK_OWNERSHIP)
                }
                current.copy(revision = mutation.revision, blocks = current.blocks.map {
                    if (it.id == mutation.block.id) mutation.block else it
                })
            }
            is FinalizeMessage -> current.copy(revision = mutation.revision, finalized = true)
        }
        val next = snapshot.map { if (it.id == current.id) updated else it }
        // Validate the whole candidate before mutating ownership or publishing, including append atomicity.
        validate(next)
        blockOwners.putAll(updated.blocks.map { it.id to updated.id })
        lastMutations[updated.id] = mutation
        mutableMessages.value = next
    }

    private fun message(id: String, revision: Long, blocks: List<ChatBlock>, finalized: Boolean): ChatMessage {
        val message = ChatMessage(id = id, revision = checkedRevision(revision), blocks = blocks, finalized = finalized)
        validate(listOf(message))
        return message
    }

    private fun validateBlockOwners(candidate: List<ChatMessage>) {
        val owners = blockOwners.toMutableMap()
        for (message in candidate) {
            for (block in message.blocks) {
                if (owners.putIfAbsent(block.id, message.id)?.let { it != message.id } == true) {
                    throw ProjectionException(ProjectionRejection.BLOCK_OWNERSHIP)
                }
            }
        }
    }

    private fun validate(candidate: List<ChatMessage>) {
        if (candidate.size > messageCapacity) throw ProjectionException(ProjectionRejection.CAPACITY)
        if (candidate.map { it.id }.toSet().size != candidate.size) {
            throw ProjectionException(ProjectionRejection.DUPLICATE_IDENTITY)
        }
        for (message in candidate) {
            if (message.id.isEmpty()) throw ProjectionException(ProjectionRejection.INVALID_IDENTITY)
            if (message.blocks.size > blockCapacity) throw ProjectionException(ProjectionRejection.CAPACITY)
            checkedRevision(message.revision)
            if (message.blocks.any { it.id.isEmpty() }) {
                throw ProjectionException(ProjectionRejection.INVALID_IDENTITY)
            }
            if (message.blocks.map { it.id }.toSet().size != message.blocks.size) {
                throw ProjectionException(ProjectionRejection.DUPLICATE_IDENTITY)
            }
        }
        validateBlockOwners(candidate)
    }

    private fun checkedRevision(revision: Long): Long {
        // The public source uses UInt64. This native boundary accepts exactly the positive Long subset;
        // a transport value above Long.MAX_VALUE is rejected before conversion, never truncated.
        if (revision <= 0) throw ProjectionException(ProjectionRejection.REVISION_RANGE)
        return revision
    }
}
