import RefractIR
import RefractMapping

/// Lowers the shared typed IR to ArkUI. Every successful return is a complete source file.
public struct ArkUIBackend: Sendable {
    public init() {}

    public func generate(module: Module, mapping: Mapping = .empty) throws -> String {
        let generation = Generation(module: module, mapping: mapping)
        return try generation.generate()
    }
}

final class Generation {
    let module: Module
    let mapping: Mapping
    var screenItemTypes: [String: String] = [:]
    var listItemTypes: [String: String] = [:]
    var accessibilityTraversal: AccessibilityTraversal?

    init(module: Module, mapping: Mapping) {
        self.module = module
        self.mapping = mapping
    }

    func generate() throws -> String {
        guard mapping.schemaVersion == 1 else {
            throw Diagnostic(code: "arkui.unsupported_mapping_version",
                             message: "ArkUI output supports mapping schema version 1, not \(mapping.schemaVersion).",
                             suggestion: "Use a version 1 refract.json.")
        }
        var writer = ArkWriter()
        // Used native declarations are resolved at their call sites; shared drivers validate unused declarations.
        writer.line("// Generated by Refract; DO NOT EDIT.")
        writer.line("// Source: \(ArkText.header(module.sourceFile))")
        let resolver = InteropResolver(module: module, mapping: mapping)
        var importLines: [String] = []
        var emittedImports: Set<String> = []
        for screen in module.screens {
            try collectImports(screen.body, resolver: resolver, into: &emittedImports)
            for parameter in screen.parameters where parameter.itemType == "RemoteImageLoader" {
                emittedImports.insert("RemoteImageLoader")
            }
            if case let .navigationStack(stack, _) = screen.body {
                try collectImports(stack, resolver: resolver, into: &emittedImports)
            }
        }
        for declaration in resolver.imports(for: .harmonyOS).sorted(by: { $0.module < $1.module })
            where declaration.symbols.contains(where: emittedImports.contains) {
            importLines.append("import { \(declaration.symbols.filter(emittedImports.contains).joined(separator: ", ")) } from '\(declaration.module)';")
        }
        for native in usedNativeComponents(in: module.screens.map(\.body)) {
            let target = try resolver.target(for: native.component, platform: .harmonyOS, location: native.location)
            if emittedImports.contains(target.symbol) && !target.module.isEmpty &&
                !resolver.imports(for: .harmonyOS).contains(where: { $0.module == target.module && $0.symbols.contains(target.symbol) }) {
                importLines.append("import { \(target.symbol) } from '\(target.module)';")
            }
        }
        for line in importLines { writer.line(line) }
        try emitEnums(module.enums, into: &writer)
        try emitArkItemTypes(module.itemTypes, into: &writer)
        try emitArkModels(module.models, into: &writer)
        for screen in module.screens {
            if case let .navigationStack(stack, _) = screen.body {
                try emitNavigationDestinations(stack, into: &writer)
            }
            guard ArkText.isIdentifier(screen.name) else {
                throw Diagnostic(code: "arkui.invalid_component_name",
                                 message: "`\(screen.name)` is not a valid ArkUI component identifier.",
                                 suggestion: "Use a Swift type name made of letters, digits and underscores.",
                                 location: screen.location)
            }
            writer.line()
            writer.line("@ComponentV2")
            writer.open("export struct \(screen.name)")
            for input in screen.parameters {
                writer.line("@Param @Require public var \(input.name): \(try input.itemType ?? input.enumName ?? arkType(input.type))\(input.isOptional ? " | null | undefined" : "")")
            }
            for state in screen.states {
                try emitLocalState(state, into: &writer)
            }
            // Local-state emission already supplies the separator before build().
            if screen.states.isEmpty, !screen.parameters.isEmpty { writer.line() }
            writer.open("build()")
            let previousItemParameters = screenItemTypes
            screenItemTypes = Dictionary(uniqueKeysWithValues: screen.parameters.compactMap { input in
                input.itemType.map { (input.name, $0) }
            })
            listItemTypes = [:]
            for state in screen.states {
                if case let .model(reference, _) = state,
                   let model = module.models.first(where: { $0.name == reference.protocolName }) {
                    for property in model.properties {
                        if let collection = property.collection {
                            screenItemTypes[reference.propertyName] = collection.itemType
                            listItemTypes[reference.propertyName] = collection.itemType
                        }
                    }
                }
            }
            defer { screenItemTypes = previousItemParameters }
            try emit(screen.body, into: &writer, mapping: mapping, resolver: resolver,
                     itemTypeName: listItemTypes.values.first)
            writer.close()
            writer.close()
        }
        return writer.text
    }

    func emit(_ node: ViewNode, into writer: inout ArkWriter, item: String? = nil,
              lazyOwner: Bool = false, mapping: Mapping = .empty,
              resolver: InteropResolver? = nil, parentAxis: ViewNode.StackAxis? = nil,
              itemTypeName: String? = nil) throws {
        switch node {
        case let .stack(axis, children, modifiers, _):
            let children = try stackChildren(children, parentAxis: axis)
            let traversal = try ArkModifiers.validateAccessibilityTraversal(modifiers, children: children, mapping: mapping)
            writer.open("\(containerName(axis))()")
            for child in children {
                let saved = accessibilityTraversal
                accessibilityTraversal = traversal
                defer { accessibilityTraversal = saved }
                try emit(child, into: &writer, item: item, mapping: mapping, resolver: resolver,
                         parentAxis: axis, itemTypeName: itemTypeName)
            }
            writer.close(suffix: try ArkModifiers.emit(modifiers, item: item, mapping: mapping))
        case let .text(value, modifiers, _):
            writer.line("Text(\(try emitLocalExpression(value, item: item, mapping: mapping)))\(try ArkModifiers.emit(modifiers, item: item, mapping: mapping, isText: true))")
        case let .button(label, action, modifiers, _):
            if case let .text(title, _, _) = label, case let .stringKey(key) = title.value {
                let resource = try mapping.stringResource(key, platform: .harmonyOS, location: title.location)
                writer.line("Button($r('\(resource.namespace ?? "app").\(resource.table ?? "string").\(resource.nativeName)'))")
            } else {
                writer.open("Button()")
                try emit(label, into: &writer, item: item, mapping: mapping, resolver: resolver)
                writer.close()
            }
            if let action {
                writer.open(".onClick(() =>")
                writer.line(try emitLocalAction(action))
                writer.close(suffix: ")")
            }
            writer.line(try ArkModifiers.emit(modifiers, item: item, mapping: mapping, traversal: accessibilityTraversal), unlessEmpty: true)
        case let .conditional(branches, location):
            guard !branches.isEmpty, branches[0].condition != nil,
                  branches.dropFirst().allSatisfy({ $0.condition != nil }) || branches.last?.condition == nil else {
                throw Diagnostic(code: "arkui.invalid_conditional",
                                 message: "A conditional must start with a condition and have at most one final else branch.",
                                 suggestion: "Use if/else if/else with a final unconditional else.",
                                 location: location)
            }
            for (index, branch) in branches.enumerated() {
                let condition = try branch.condition.map { try emitLocalExpression($0, item: item, mapping: mapping) }
                if index == 0 {
                    guard let condition else {
                        throw Diagnostic(code: "arkui.invalid_conditional", message: "A conditional needs a first condition.", location: location)
                    }
                    writer.open("if (\(condition))")
                } else {
                    writer.closeBranch(condition.map { "else if (\($0))" } ?? "else")
                }
                for child in branch.children { try emit(child, into: &writer, item: item, mapping: mapping, resolver: resolver) }
            }
            writer.close()
        case let .switchExpression(subject, enumName, cases, _):
            try emitEnumSwitch(subject: subject, enumName: enumName, cases: cases,
                               into: &writer, mapping: mapping, resolver: resolver)
        case let .navigationStack(stack, _):
            for child in stack.content {
                try emit(child, into: &writer, mapping: mapping, resolver: resolver)
            }
        case let .navigationLink(title, pathName, enumName, destination, _):
            try emitNavigationLink(title: title, pathName: pathName, enumName: enumName,
                                   destination: destination, into: &writer, mapping: mapping)
        case let .nativeModifier(child, operations, location):
            var modifiers: [Modifier] = []
            for operation in operations {
                switch operation.operation {
                case let .testTag(value):
                    modifiers.append(Modifier(name: "nativeTestTag", arguments: [value], argumentLabels: [nil],
                                              location: operation.location))
                case let .contentDescription(value):
                    modifiers.append(Modifier(name: "accessibilityLabel", arguments: [value], argumentLabels: [nil],
                                              location: operation.location))
                case .contentType:
                    throw Diagnostic(code: "RFNATIVE004",
                        message: "Row content type belongs on a generated child, not a native measurement wrapper.",
                        suggestion: "Apply `.contentType` directly to the generated child row",
                        location: operation.location ?? location)
                case .retainCallback:
                    throw Diagnostic(code: "RFNATIVE004",
                        message: "HarmonyOS callback retention requires a typed callback-identity representation.",
                        suggestion: "Use a direct typed callback; do not discard the retention operation or add a runtime cache.",
                        location: operation.location ?? location)
                }
            }
            guard let modified = child.appendingModifier(contentsOf: modifiers) else {
                throw Diagnostic(code: "RFNATIVE004", message: "The native test id cannot be attached to this ArkUI receiver.",
                                 suggestion: "Apply testTag to a concrete view or container.", location: location)
            }
            try emit(modified, into: &writer, item: item, lazyOwner: lazyOwner, mapping: mapping, resolver: resolver)
        case let .optionalBinding(subject, binding, children, otherwise, location):
            try emitOptionalBinding(subject: subject, binding: binding, children: children, otherwise: otherwise,
                                    location: location, into: &writer, mapping: mapping, resolver: resolver)
        case let .native(component, location):
            guard let resolver else {
                throw Diagnostic(code: "arkui.unresolved_native_component",
                                 message: "Native component `\(component.name)` has no resolved ArkUI declaration.",
                                 suggestion: "Declare its ArkUI symbol and typed parameters in refract.json.",
                                 location: location)
            }
            let target = try resolver.target(for: component, platform: .harmonyOS, location: location)
            let arguments = try InteropEmission.arguments(for: component, target: target) {
                try ArkExpression.emit($0, item: item, mapping: mapping)
            }
            writer.line("\(target.symbol)({ \(arguments.joined(separator: ", ")) })")
        case let .component(component, location):
            try ArkDesignSystem().emit(component, location: location, mapping: mapping, writer: &writer)
        case let .child(child, _):
            let arguments = try child.arguments.map { argument in
                if child.item == argument {
                    return "\(argument.label): \(try emitLocalExpression(Expression(.reference(argument.expression)), item: item))"
                }
                return "\(argument.label): this.\(argument.expression)"
            }
            writer.line("\(child.name)({ \(arguments.joined(separator: ", ")) })")
            if let contentType = child.contentType {
                guard item != nil else {
                    throw Diagnostic(code: "RFNATIVE004",
                        message: "A reusable row content type requires a generated child directly owned by a dynamic List.",
                        suggestion: "Apply `.contentType(\"setting\")` to the generated child inside the model-backed List",
                        location: node.sourceLocation)
                }
                writer.line(".reuse({ reuseId: () => '\(contentType)' })")
            }
        case let .toggle(title, value, modifiers, nativeModifiers, labelsHidden, location):
            try emitExtended(.toggle(title: title, value: value, modifiers: modifiers, nativeModifiers: nativeModifiers,
                                     labelsHidden: labelsHidden, location: location),
                             into: &writer, item: item, mapping: mapping, resolver: resolver,
                             itemParameters: screenItemTypes, itemTypeName: itemTypeName)
        case let .platformView(alternatives, _):
            for child in alternatives.harmonyOS {
                try emit(child, into: &writer, item: item, lazyOwner: lazyOwner, mapping: mapping, resolver: resolver)
            }
        default:
            try emitExtended(node, into: &writer, item: item, lazyOwner: lazyOwner, mapping: mapping, resolver: resolver)
        }
    }

    private func arkType(_ type: ValueType) throws -> String {
        switch type {
        case .string: "string"
        case .int, .double: "number"
        case .bool: "boolean"
        }
    }

    private func usedNativeComponents(in bodies: [ViewNode]) -> [(component: NativeComponent, location: RefractIR.SourceLocation?)] {
        func collect(_ node: ViewNode, into result: inout [(component: NativeComponent, location: RefractIR.SourceLocation?)]) {
            if case let .native(component, location) = node { result.append((component, location)) }
            if case let .navigationStack(stack, _) = node {
                for destination in stack.destinations where destination.model == nil {
                    result.append((NativeComponent(name: destination.viewName), node.sourceLocation))
                }
            }
            for child in node.children(for: .harmonyOS) { collect(child, into: &result) }
        }
        var result: [(component: NativeComponent, location: RefractIR.SourceLocation?)] = []
        for body in bodies { collect(body, into: &result) }
        return result
    }

    private func collectImports(_ node: ViewNode, resolver: InteropResolver, into emittedImports: inout Set<String>) throws {
        for child in node.children(for: .harmonyOS) { try collectImports(child, resolver: resolver, into: &emittedImports) }
        if case let .native(component, location) = node {
            emittedImports.insert(try resolver.target(for: component, platform: .harmonyOS, location: location).symbol)
        }
        collectModifierImports(node, mapping: mapping, into: &emittedImports)
        if case let .component(component, location) = node {
            emittedImports.insert(try mapping.component(named: component.name, platform: .harmonyOS,
                                                       location: location).target)
            for modifier in component.modifiers {
                for argument in modifier.arguments {
                    if case let .reference(reference) = argument.value {
                        for category in TokenCategory.allCases {
                            if let target = mapping.harmonyOS.tokens[category][reference] {
                                emittedImports.insert(target.split(separator: ".").first.map(String.init) ?? target)
                            }
                        }
                    }
                }
            }
        }
    }

    private func collectImports(_ stack: NavigationStackNode, resolver: InteropResolver,
                                into emittedImports: inout Set<String>) throws {
        for destination in stack.destinations where destination.model == nil {
            emittedImports.insert(try resolver.target(for: NativeComponent(name: destination.viewName),
                                                     platform: .harmonyOS, location: nil).symbol)
        }
    }

    private func collectModifierImports(_ node: ViewNode, mapping: Mapping, into emittedImports: inout Set<String>) {
        let modifiers: [Modifier]
        switch node {
        case let .stack(_, _, values, _), let .layout(_, _, values, _), let .scroll(_, _, values, _),
             let .list(_, values, _), let .text(_, values, _), let .button(_, _, values, _),
             let .image(_, values, _), let .toggle(_, _, values, _, _, _), let .textInput(_, _, values, _),
             let .label(_, _, values, _), let .divider(values, _):
            modifiers = values
        default:
            return
        }
        for modifier in modifiers {
            for argument in modifier.arguments {
                for expression in [argument] + platformBranches(argument) {
                    guard case let .reference(name) = expression.value, name.contains(".") else { continue }
                    for category in TokenCategory.allCases {
                        guard let target = mapping.harmonyOS.tokens[category][name] else { continue }
                        emittedImports.insert(target.split(separator: ".").first.map(String.init) ?? target)
                    }
                }
            }
        }
    }

    private func platformBranches(_ expression: Expression) -> [Expression] {
        guard case let .platformValue(alternatives) = expression.value else { return [] }
        return [alternatives.android, alternatives.harmonyOS]
    }

    private func containerName(_ axis: ViewNode.StackAxis) -> String {
        switch axis {
        case .vertical: "Column"
        case .horizontal: "Row"
        case .depth: "Stack"
        }
    }
}

private extension StateDeclaration {
    var location: RefractIR.SourceLocation? {
        switch self {
        case let .state(_, _, _, location), let .binding(_, _, location), let .model(_, location),
             let .navigationPath(_, _, location): location
        }
    }
}

struct ArkWriter {
    private(set) var text = ""
    var depth = 0

    mutating func line(_ value: String = "", unlessEmpty: Bool = false) {
        if value.isEmpty {
            if !unlessEmpty { text += "\n" }
            return
        }
        for line in value.split(separator: "\n", omittingEmptySubsequences: false) {
            let continuation = line.hasPrefix("\u{1}")
            let content = continuation ? line.dropFirst() : line
            text += String(repeating: "  ", count: depth + (continuation ? 1 : 0)) + content + "\n"
        }
    }

    mutating func open(_ value: String) {
        line(value + " {")
        depth += 1
    }

    mutating func closeBranch(_ continuation: String) {
        close(suffix: " \(continuation) {")
        depth += 1
    }

    mutating func close(suffix: String = "") {
        precondition(depth > 0)
        depth -= 1
        line("}" + suffix)
    }
}
