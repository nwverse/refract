import RefractIR
import RefractMapping

public struct ComposeBackend: Sendable {
    public init() {}

    public func generate(module: Module, mapping: Mapping = .empty) throws -> String {
        var out = GeneratedSource(header: "// Generated by Refract; DO NOT EDIT.\n// Source: \(module.sourceFile)\n")
        out.line("package refract.generated")
        out.line()
        out.line("import androidx.compose.foundation.layout.Arrangement")
        out.line("import androidx.compose.foundation.layout.Column")
        out.line("import androidx.compose.foundation.layout.Row")
        out.line("import androidx.compose.material3.Button")
        out.line("import androidx.compose.material3.Text")
        out.line("import androidx.compose.runtime.Composable")
        out.line("import androidx.compose.ui.unit.dp")
        for screen in module.screens {
            out.line()
            out.line("@Composable")
            out.open("public fun \(screen.name)()")
            try emit(screen.body, into: &out)
            out.close()
        }
        return out.text
    }

    private func emit(_ node: ViewNode, into out: inout GeneratedSource) throws {
        switch node {
        case let .stack(axis, children, _, _):
            out.open(axis == .horizontal ? "Row(horizontalArrangement = Arrangement.spacedBy(8.dp))" : "Column(verticalArrangement = Arrangement.spacedBy(8.dp))")
            try children.forEach { try emit($0, into: &out) }
            out.close()
        case let .text(expression, _, _):
            out.line("Text(text = \(string(expression)))")
        case let .button(label, _, _, _):
            out.open("Button(onClick = { })")
            try emit(label, into: &out)
            out.close()
        case .native, .conditional, .platformView:
            throw Diagnostic(code: "unsupportedBackendNode",
                             message: "This IR node is not supported by the Compose backend yet.",
                             suggestion: "Use the currently supported views or extend the backend.")
        }
    }

    private func string(_ expression: Expression) -> String {
        switch expression.value {
        case let .stringLiteral(value): return "\"\(value)\""
        case let .stringKey(value): return "\"\(value)\""
        case let .reference(value): return value
        default: return "\"\""
        }
    }
}

struct GeneratedSource {
    private(set) var text: String
    private var depth = 0

    init(header: String) { text = header }
    mutating func line(_ value: String = "") {
        text += value.isEmpty ? "\n" : String(repeating: "    ", count: depth) + value + "\n"
    }
    mutating func open(_ value: String) { line(value + " {"); depth += 1 }
    mutating func close() { depth -= 1; line("}") }
}
