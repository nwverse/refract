import RefractIR
import RefractMapping

/// Lowers the platform-neutral IR into idiomatic Jetpack Compose source.
///
/// The contract for the emitted Kotlin is `docs/compose-backend.md`. The state and observation rules this
/// backend follows are in `docs/state-and-models.md`. This file owns only the Compose shape: which composable
/// to call, how `Modifier` is chained, where lambdas are remembered, and which diagnostics to raise. No Refract
/// runtime is referenced from the output.
public struct ComposeBackend: Sendable {
    public init() {}

    public func generate(module: Module, mapping: Mapping = .empty) throws -> String {
        var context = Context(module: module, mapping: mapping)
        // Native references validate both target signatures at each call site below.
        // Render the body first so we know which imports are needed.
        var bodyWriter = KotlinWriter()
        if module.models.contains(where: { !$0.properties.isEmpty }) {
            context.imports.insert("androidx.compose.runtime.State")
        }
        try emitEnumDeclarations(module.enums, into: &bodyWriter)
        try emitComposeItemTypes(module.itemTypes, into: &bodyWriter, context: &context)
        try emitComposeModels(module.models, into: &bodyWriter)
        for screen in module.screens {
            try emit(screen, into: &bodyWriter, context: &context)
            if case let .navigationStack(stack, _) = screen.body {
                for destination in stack.destinations where destination.model == nil {
                    _ = try InteropResolver(module: module, mapping: mapping)
                        .target(for: NativeComponent(name: destination.viewName), platform: .android, location: screen.location)
                }
                try emitNavigationDestinations(stack, into: &bodyWriter, context: &context)
            }
        }

        var out = KotlinWriter()
        out.line("// Generated by Refract; DO NOT EDIT.")
        out.line("// Source: \(module.sourceFile)")
        out.line("@file:Suppress(\"RemoveRedundantQualifierName\")")
        out.line()
        out.line("package \(context.packageName)")
        out.line()
        for item in InteropResolver(module: module, mapping: mapping).imports(for: .android) {
            context.imports.insert(item.module)
        }
        let usedNativeNames = selectedNativeNames(in: module.screens.map(\.body))
        for item in mapping.android.nativeComponents.sorted(by: { $0.key < $1.key }) {
            if usedNativeNames.contains(item.key), let module = item.value.module {
                context.imports.insert("\(module).\(item.value.target)")
            }
        }
        for item in context.imports.sorted() {
            out.line("import \(item)")
        }
        out.append(bodyWriter.text)
        return out.text
    }

    private func selectedNativeNames(in bodies: [ViewNode]) -> Set<String> {
        func collect(_ node: ViewNode, into names: inout Set<String>) {
            if case let .native(component, _) = node { names.insert(component.name) }
            if case let .navigationStack(stack, _) = node {
                for destination in stack.destinations where destination.model == nil {
                    names.insert(destination.viewName)
                }
            }
            for child in node.children(for: .android) { collect(child, into: &names) }
        }
        var names: Set<String> = []
        for body in bodies { collect(body, into: &names) }
        return names
    }

    private func emit(_ screen: Screen, into out: inout KotlinWriter, context: inout Context) throws {
        out.line()
        out.line("@Composable")
        let parameters = parameterList(for: screen, context: &context)
        if parameters.isEmpty {
            out.open("public fun \(screen.name)(modifier: Modifier = Modifier)")
            try emitStates(screen.states, into: &out, context: &context)
            try emit(screen.body, isRoot: true, into: &out, context: &context)
            out.close()
        } else {
            out.line("public fun \(screen.name)(")
            out.depth += 1
            for parameter in parameters {
                out.line("\(parameter),")
            }
            out.line("modifier: Modifier = Modifier,")
            out.depth -= 1
            out.line(") {")
            out.depth += 1
            try emitStates(screen.states, into: &out, context: &context)
            try emit(screen.body, isRoot: true, into: &out, context: &context)
            out.depth -= 1
            out.line("}")
        }
    }

    // MARK: - Parameters and state

    private func parameterList(for screen: Screen, context: inout Context) -> [String] {
        var parameters: [String] = []
        for input in screen.parameters {
            context.imports.insert("androidx.compose.ui.Modifier")
            parameters.append("\(input.name): \(input.itemType ?? input.enumName ?? kotlinType(input.type))\(input.isOptional ? "?" : "")")
        }
        for state in screen.states {
            switch state {
            case let .binding(name, type, _):
                context.imports.insert("androidx.compose.ui.Modifier")
                parameters.append("\(name): \(kotlinType(type))")
                parameters.append("on\(name.uppercasingFirst())Change: (\(kotlinType(type))) -> Unit")
            case let .navigationPath(name, enumName, _):
                parameters.append("on\(name.uppercasingFirst())Navigate: (\(enumName)) -> Unit")
            case let .model(reference, _):
                if context.module.models.contains(where: {
                    $0.name == reference.protocolName && !$0.properties.isEmpty
                }) {
                    context.imports.insert("androidx.compose.runtime.State")
                }
                parameters.append("\(reference.propertyName): \(reference.protocolName)")
            case .state:
                // Local state is remembered inside the body, not a parameter.
                continue
            }
        }
        return parameters
    }

    private func emitStates(_ states: [StateDeclaration], into out: inout KotlinWriter, context: inout Context) throws {
        for state in states {
            if case .state = state {
                context.imports.insert("androidx.compose.runtime.getValue")
                context.imports.insert("androidx.compose.runtime.setValue")
            }
            if case let .state(name, type, initial, _) = state {
                context.imports.insert("androidx.compose.runtime.remember")
                context.imports.insert("androidx.compose.runtime.mutableStateOf")
                let initialText = try renderExpression(initial ?? defaultInitial(type), context: &context)
                out.line("var \(name) by remember { mutableStateOf(\(initialText)) }")
            }
        }
    }

    private func defaultInitial(_ type: ValueType) -> Expression {
        switch type {
        case .string: return Expression(.stringLiteral(""))
        case .bool: return Expression(.boolLiteral(false))
        case .int, .double: return Expression(.numberLiteral("0"))
        }
    }

    // MARK: - Views

    func emit(_ node: ViewNode, isRoot: Bool = false, parentAxis: ViewNode.StackAxis? = nil,
              into out: inout KotlinWriter, context: inout Context) throws {
        switch node {
        case let .stack(axis, children, modifiers, location):
            try emitStack(axis: axis, children: children, modifiers: modifiers, isRoot: isRoot,
                          parentAxis: parentAxis, location: location, into: &out, context: &context)
        case .layout, .scroll, .list, .section, .listItem, .forEach, .image, .textInput,
             .label, .divider, .spacer:
            try emitTyped(node, isRoot: isRoot, parentAxis: parentAxis, into: &out, context: &context)
        case let .toggle(title, value, modifiers, nativeModifiers, labelsHidden, location):
            try emitToggle(title: title, value: value, modifiers: modifiers, nativeModifiers: nativeModifiers, isRoot: isRoot,
                           labelsHidden: labelsHidden, location: location, into: &out, context: &context)
        case let .text(expression, modifiers, location):
            try emitText(expression, modifiers: modifiers, isRoot: isRoot, parentAxis: parentAxis, location: location,
                         into: &out, context: &context)
        case let .button(label, action, modifiers, location):
            try emitButton(label: label, action: action, modifiers: modifiers, isRoot: isRoot,
                           location: location, into: &out, context: &context)
        case let .navigationStack(stack, location):
            try emitNavigationStack(stack, isRoot: isRoot, location: location, into: &out, context: &context)
        case let .navigationLink(title, pathName, enumName, destination, location):
            try emitNavigationLink(title: title, pathName: pathName, enumName: enumName,
                                   destination: destination, location: location, into: &out, context: &context)
        case let .native(component, location):
            try emitNative(component, location: location, isRoot: isRoot, into: &out, context: &context)
        case let .nativeModifier(child, operations, _):
            try ComposeNativeModifier().emit(child, operations: operations, isRoot: isRoot,
                                             into: &out, context: &context)
        case let .component(component, location):
            try emitDesignSystem(component, location: location, isRoot: isRoot, into: &out, context: &context)
        case let .child(child, _):
            let arguments = child.arguments.map { "\($0.label) = \($0.expression)" }
            out.line("\(child.name)(\(arguments.joined(separator: ", ")))")
        case let .platformView(alternatives, _):
            // The Android branch is selected at build time; no runtime dispatch is emitted.
            for child in alternatives.android {
                try emit(child, isRoot: isRoot, parentAxis: parentAxis, into: &out, context: &context)
            }
        case let .switchExpression(subject, enumName, cases, location):
            try emitEnumSwitch(subject: subject, enumName: enumName, cases: cases, isRoot: isRoot,
                               location: location, into: &out, context: &context)
        case let .conditional(branches, location):
            try emitControlFlow(branches, isRoot: isRoot, location: location, into: &out, context: &context)
        case let .optionalBinding(subject, binding, children, otherwise, location):
            try emitOptionalBinding(subject: subject, binding: binding, children: children, otherwise: otherwise,
                                    isRoot: isRoot, location: location, into: &out, context: &context)
        }
    }

    private func emitStack(axis: ViewNode.StackAxis, children: [ViewNode], modifiers: [Modifier],
                           isRoot: Bool, parentAxis: ViewNode.StackAxis?, location: SourceLocation?, into out: inout KotlinWriter,
                           context: inout Context) throws {
        let call: String
        switch axis {
        case .vertical:
            context.imports.insert("androidx.compose.foundation.layout.Column")
            call = "Column"
        case .horizontal:
            context.imports.insert("androidx.compose.foundation.layout.Row")
            call = "Row"
        case .depth:
            context.imports.insert("androidx.compose.foundation.layout.Box")
            call = "Box"
        }
        let modifierChain = try modifierChain(modifiers, isRoot: isRoot, parentAxis: parentAxis, context: &context)
        out.open("\(call)(modifier = \(modifierChain))")
        for child in children {
            try emit(child, parentAxis: axis, into: &out, context: &context)
        }
        out.close()
    }

    private func emitText(_ expression: Expression, modifiers: [Modifier], isRoot: Bool, parentAxis: ViewNode.StackAxis?,
                          location: SourceLocation?, into out: inout KotlinWriter,
                          context: inout Context) throws {
        context.imports.insert("androidx.compose.material3.Text")
        let text = try renderExpression(expression, context: &context)
        let modifierChain = try modifierChain(modifiers, isRoot: isRoot, isText: true, parentAxis: parentAxis, context: &context)
        let textModifiers = try textSpecificModifiers(modifiers, context: &context)
        var arguments = ["text = \(text)"]
        let styled = modifiers.contains { $0.argumentLabels.contains(where: { $0 != nil }) || $0.name == "foregroundStyle" }
        if modifierChain != "Modifier" {
            if modifierChain.contains(".background(") {
                arguments.append("modifier = \(modifierChain.replacingOccurrences(of: ").", with: ")\n        ."))")
            } else {
                arguments.append("modifier = \(modifierChain)")
            }
        }
        if styled {
            for modifier in modifiers where ["font", "foregroundStyle", "foregroundColor"].contains(modifier.name) {
                let value = try composeToken(try ModifierArguments(modifier: modifier).one(),
                    category: modifier.name == "font" ? .font : .color, context: &context)
                arguments.append("\(modifier.name == "font" ? "style" : "color") = \(value)")
            }
        } else {
            arguments.append(contentsOf: textModifiers)
        }
        if arguments.count == 1 {
            out.line("Text(\(arguments[0]))")
        } else {
            out.line("Text(")
            out.depth += 1
            for argument in arguments {
                out.line("\(argument),")
            }
            out.depth -= 1
            out.line(")")
        }
    }

    private func emitButton(label: ViewNode, action: StateAction?, modifiers: [Modifier], isRoot: Bool,
                            location: SourceLocation?, into out: inout KotlinWriter,
                            context: inout Context) throws {
        context.imports.insert("androidx.compose.material3.Button")
        let modifierChain = try modifierChain(modifiers, isRoot: isRoot, context: &context)
        let onClick: String
        if modifiers.contains(where: { $0.name == "retainCallback" }) {
            onClick = "onClick"
        } else if let action {
            onClick = "{ \(try renderAction(action, context: &context)) }"
        } else {
            onClick = "{ }"
        }
        out.open("Button(onClick = \(onClick), modifier = \(modifierChain))")
        try emit(label, into: &out, context: &context)
        out.close()
    }

    func emitNative(_ component: NativeComponent, location: SourceLocation?, isRoot: Bool,
                            into out: inout KotlinWriter, context: inout Context) throws {
        let resolver = InteropResolver(module: context.module, mapping: context.mapping)
        let target = try resolver.target(for: component, platform: .android, location: location)
        var arguments = try InteropEmission.arguments(for: component, target: target) {
            try renderExpression($0, context: &context)
        }
        if isRoot, let modifier = resolver.nativeComponent(for: component, platform: .android)?.modifierParameter {
            arguments.append("\(modifier) = modifier")
        }
        out.line("\(target.symbol)(\(arguments.joined(separator: ", ")))")
    }

    private func emitDesignSystem(_ component: ComponentReference, location: SourceLocation?, isRoot: Bool,
                                  into out: inout KotlinWriter, context: inout Context) throws {
        let source = try ComposeDesignSystem().emit(component, location: location, isRoot: isRoot,
            mapping: context.mapping, addImport: { context.imports.insert($0) })
        for line in source.split(separator: "\n", omittingEmptySubsequences: false) {
            out.line(String(line))
        }
    }

    // MARK: - Expressions

    func renderExpression(_ expression: Expression, context: inout Context) throws -> String {
        switch expression.value {
        case let .stringLiteral(value):
            return "\"\(value.escapedForKotlin())\""
        case let .verbatimText(value):
            return "\"\(value.escapedForKotlin())\""
        case .stringKey:
            throw Diagnostic(code: "R.string.unsupported_expression",
                             message: "A string key must be validated as localized text before emission.",
                             suggestion: "Use a static localization key through the localization frontend",
                             location: expression.location)
        case .localizedText:
            context.imports.insert("androidx.compose.ui.res.stringResource")
            if let resourceClass = context.androidResourceClass, resourceClass == "\(context.packageName).R" {
                context.imports.insert(resourceClass)
            }
            return try LocalizedTextEmitter.compose(expression, mapping: context.mapping,
                                                     packageName: context.packageName) {
                try renderExpression($0, context: &context)
            }
        case let .boolLiteral(value):
            return value ? "true" : "false"
        case let .numberLiteral(text):
            return text
        case let .layoutSpacing(token):
            return String(token.points)
        case let .reference(name):
            return name
        case let .binding(name):
            return name
        case let .valueProperty(.state(name)):
            return name
        case let .valueProperty(.binding(name)):
            return name
        case let .valueProperty(.model(model, property)):
            return "\(model).\(property).value"
        case let .valueProperty(.itemBinding(binding)):
            return "\(binding.item).\(binding.property)"
        case let .interpolatedString(segments):
            var result = "\""
            for segment in segments {
                switch segment {
                case let .literal(text): result += text.escapedForKotlin()
                case let .expression(value): result += "${\(try renderExpression(value, context: &context))}"
                }
            }
            return result + "\""
        case let .platformValue(alternatives):
            return try renderExpression(alternatives.android, context: &context)
        }
    }

    func renderAction(_ action: StateAction, context: inout Context) throws -> String {
        switch action {
        case let .assign(.state(name), value):
            return "\(name) = \(try renderExpression(value, context: &context))"
        case let .increment(.state(name), value):
            return "\(name) += \(try renderExpression(value, context: &context))"
        case let .assign(.binding(name), value):
            return "on\(name.uppercasingFirst())Change(\(try renderExpression(value, context: &context)))"
        case let .increment(.binding(name), value):
            return "on\(name.uppercasingFirst())Change(\(name) + \(try renderExpression(value, context: &context)))"
        case let .modelMethod(model, name, arguments):
            let arguments = try arguments.map { argument -> String in
                let value = try renderExpression(argument.value, context: &context)
                return argument.label.map { "\($0) = \(value)" } ?? value
            }.joined(separator: ", ")
            return "\(model).\(name)(\(arguments))"
        }
    }

    func kotlinType(_ type: ValueType) -> String {
        switch type {
        case .string: return "String"
        case .bool: return "Boolean"
        case .int: return "Int"
        case .double: return "Double"
        }
    }

    // MARK: - Context

    struct Context {
        var packageName: String = "refract.generated"
        var imports: Set<String> = [
            "androidx.compose.runtime.Composable",
            "androidx.compose.ui.Modifier",
        ]
        let mapping: Mapping
        let module: Module
        var androidResourceClass: String?
        var retainedItem: (name: String, type: String)?

        init(module: Module, mapping: Mapping) {
            self.mapping = mapping
            self.module = module
            self.androidResourceClass = mapping.android.resources.className
            if let packageName = mapping.android.output.packageName {
                self.packageName = packageName
            }
        }
    }
}

// MARK: - Writer

struct KotlinWriter {
    private(set) var text: String = ""
    var depth: Int = 0

    mutating func line(_ value: String = "") {
        if value.isEmpty {
            text += "\n"
        } else {
            text += String(repeating: "    ", count: depth) + value + "\n"
        }
    }

    mutating func open(_ value: String) {
        if value.hasSuffix("(") {
            line(value)
            depth += 1
        } else {
            line(value + " {")
            depth += 1
        }
    }

    mutating func close() {
        depth -= 1
        line("}")
    }

    mutating func append(_ other: String) {
        text += other
    }
}

// MARK: - Helpers

extension String {
    func uppercasingFirst() -> String {
        guard let first else { return self }
        return first.uppercased() + dropFirst()
    }

    func escapedForKotlin() -> String {
        var result = ""
        for char in self {
            switch char {
            case "\\": result += "\\\\"
            case "\"": result += "\\\""
            case "\n": result += "\\n"
            case "\t": result += "\\t"
            case "\r": result += "\\r"
            case "$": result += "\\$"
            default: result.append(char)
            }
        }
        return result
    }
}
