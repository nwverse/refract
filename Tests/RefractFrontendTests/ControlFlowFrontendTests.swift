import RefractArkUI
import RefractCompose
import RefractFrontend
import RefractIR
import Testing

private let conditionalSource = """
protocol StatusModel: RefractModel {
    var isEnabled: Bool { get }
}

struct ConditionalContent: View {
    let model: StatusModel

    var body: some View {
        if model.isEnabled {
            Text(verbatim: "Enabled")
        } else {
            Text(verbatim: "Disabled")
        }
    }
}
"""

@Test func booleanConditionalGeneratesExactNativeSource() throws {
    let unit = Frontend.parse(SourceFile(path: "Input.swift", contents: conditionalSource))
    #expect(unit.diagnostics.isEmpty)
    let kotlin = try ComposeBackend().generate(module: unit.module)
    #expect(kotlin == """
    // Generated by Refract; DO NOT EDIT.
    // Source: Input.swift
    @file:Suppress("RemoveRedundantQualifierName")

    package refract.generated

    import androidx.compose.foundation.layout.Box
    import androidx.compose.material3.Text
    import androidx.compose.runtime.Composable
    import androidx.compose.runtime.State
    import androidx.compose.ui.Modifier

    public interface StatusModel {
        public val isEnabled: State<Boolean>
    }

    @Composable
    public fun ConditionalContent(
        model: StatusModel,
        modifier: Modifier = Modifier,
    ) {
        Box(modifier = modifier) {
            if (model.isEnabled.value) {
                Text(text = "Enabled")
            } else {
                Text(text = "Disabled")
            }
        }
    }

    """)
    let arkTS = try ArkUIBackend().generate(module: unit.module)
    #expect(arkTS == """
    // Generated by Refract; DO NOT EDIT.
    // Source: Input.swift

    export interface StatusModel {
      isEnabled: boolean;
    }

    @ComponentV2
    export struct ConditionalContent {
      @Require @Param model: StatusModel;

      build() {
        if (this.model.isEnabled) {
          Text('Enabled')
        } else {
          Text('Disabled')
        }
      }
    }

    """)
    #expect(!kotlin.contains("AnyView"))
    #expect(!arkTS.contains("AnyView"))
    #expect(!kotlin.contains("RefractRuntime"))
    #expect(!arkTS.contains("RefractRuntime"))
}

@Test func nestedConditionalUsesTypedBindingAndPreservesBranchOrder() throws {
    let unit = Frontend.parse(SourceFile(path: "Input.swift", contents: """
    struct ConditionalRows: View {
        @Binding var isLoading: Bool
        @State private var hasError: Bool = false

        var body: some View {
            VStack {
                if isLoading {
                    Text(verbatim: "Loading")
                } else if hasError {
                    Text(verbatim: "Failed")
                } else {
                    Text(verbatim: "Ready")
                }
            }
        }
    }
    """))
    #expect(unit.diagnostics.isEmpty)
    let kotlin = try ComposeBackend().generate(module: unit.module)
    #expect(kotlin.contains("""
        Column(modifier = modifier) {
            if (isLoading) {
                Text(text = "Loading")
            } else if (hasError) {
                Text(text = "Failed")
            } else {
                Text(text = "Ready")
            }
        }
    """))
    let arkTS = try ArkUIBackend().generate(module: unit.module)
    #expect(arkTS.contains("if (this.isLoading) {"))
    #expect(arkTS.contains("} else if (this.hasError) {"))
    #expect(arkTS.contains("Text('Loading')"))
    #expect(arkTS.contains("Text('Ready')"))
}

@Test(arguments: [
    ("if let value = Optional(true) { Text(verbatim: \"Bound\") }", "RFCTRL002"),
    ("if case .some(true) = Optional(true) { Text(verbatim: \"Matched\") }", "RFCTRL005"),
    ("if value is AnyObject { Text(verbatim: \"Cast\") }", "RFCTRL004"),
    ("switch value { default: Text(verbatim: \"Default\") }", "RFCTRL003"),
])
func unsupportedConditionalFormsHaveCodedDiagnostics(_ body: String, _ code: String) {
    let unit = Frontend.parse(SourceFile(path: "Input.swift", contents: """
    struct RejectedConditional: View {
        var body: some View {
            \(body)
        }
    }
    """))
    #expect(unit.diagnostics.map(\.code) == [code])
    #expect(unit.module.screens.isEmpty)
}

@Test func nonBooleanConditionIsRejectedInsteadOfCoerced() {
    let unit = Frontend.parse(SourceFile(path: "Input.swift", contents: """
    protocol CountModel: RefractModel { var count: Int { get } }
    struct RejectedCondition: View {
        let model: CountModel
        var body: some View {
            if model.count { Text(verbatim: "Wrong") }
        }
    }
    """))
    #expect(unit.diagnostics.map(\.code) == ["RFCTRL001"])
    #expect(unit.module.screens.isEmpty)
}
