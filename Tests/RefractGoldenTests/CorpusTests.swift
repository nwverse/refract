import Foundation
import Testing
import RefractGolden
import RefractMapping

struct SubsetCorpusTests {
    @Test
    func handWrittenContractCasesAreComplete() throws {
        let fixtures = try CorpusLoader.load(repository: GoldenTests.repository)
        let cases = fixtures.filter { $0.name.hasPrefix("v0-") }
        #expect(cases.count >= 20)
        #expect(cases.filter { $0.expectedDiagnostics != nil }.count >= 1)
        #expect(cases.filter { $0.expectedKotlin != nil && $0.expectedArkTS != nil }.count >= 1)
        #expect(fixtures.contains { $0.status == .ready && $0.expectedDiagnostics == nil })

        for fixture in cases {
            #expect(!fixture.input.isEmpty, Comment(rawValue: "\(fixture.name) must have Swift input"))
            if let expected = fixture.expectedDiagnostics {
                #expect(!expected.isEmpty)
                for line in expected.split(separator: "\n") {
                    #expect(line.contains(": error ["), "Diagnostic must have a source and stable code")
                    #expect(line.contains(" Suggestion: "), "Diagnostic must suggest a supported alternative")
                }
            }
            for expected in [fixture.expectedKotlin, fixture.expectedArkTS] {
                if let expected {
                    #expect(expected.hasPrefix("// Generated by Refract; DO NOT EDIT.\n// Source: Input.swift\n"))
                }
            }
            if let expected = fixture.expectedKotlin {
                #expect(expected.contains("modifier: Modifier = Modifier"),
                        Comment(rawValue: "\(fixture.name) needs the public native call-site modifier"))
            }
            if let expected = fixture.expectedArkTS {
                #expect(!expected.contains("@Entry"), "A reusable component must not own the application entry point")
                #expect(!expected.contains("@Component\n"), "V0 uses state management V2")
            }
            if let mapping = fixture.mapping {
                #expect(throws: Never.self) { _ = try JSONSerialization.jsonObject(with: Data(mapping.utf8)) }
            }
            if fixture.status == .ready, let mapping = fixture.mapping {
                #expect(throws: Never.self) {
                    _ = try Mapping.load(data: Data(mapping.utf8), file: "refract.json")
                }
            }
        }
    }

    @Test
    func pendingMappingFilesMatchThePublishedSchema() throws {
        for fixture in try CorpusLoader.load(repository: GoldenTests.repository) where fixture.name.hasPrefix("v0-") {
            guard fixture.mapping != nil else { continue }
            let directory = GoldenTests.repository.appendingPathComponent("Fixtures/\(fixture.name)")
            #expect(throws: Never.self, Comment(rawValue: "Mapping must match the published schema in \(fixture.name)")) {
                _ = try Mapping.load(contentsOf: directory.appendingPathComponent("refract.json"))
            }
        }
    }

    @Test
    func nativeStringCatalogsMatchTheirMappings() throws {
        for fixture in try CorpusLoader.load(repository: GoldenTests.repository) where fixture.name.hasPrefix("v0-") {
            guard let mapping = fixture.mapping,
                  let data = mapping.data(using: .utf8),
                  let object = try JSONSerialization.jsonObject(with: data) as? [String: Any],
                  let android = object["android"] as? [String: Any],
                  let harmony = object["harmonyOS"] as? [String: Any],
                  let androidResources = android["resources"] as? [String: Any],
                  let harmonyResources = harmony["resources"] as? [String: Any],
                  let androidKeys = androidResources["strings"] as? [String: String],
                  let harmonyKeys = harmonyResources["strings"] as? [String: String],
                  let androidPath = androidResources["catalog"] as? String,
                  let harmonyPath = harmonyResources["catalog"] as? String else { continue }
            #expect(androidKeys == harmonyKeys, Comment(rawValue: "Resource registries must agree in \(fixture.name)"))
            let directory = GoldenTests.repository.appendingPathComponent("Fixtures/\(fixture.name)")
            let androidCatalog = directory.appendingPathComponent(androidPath)
            let harmonyCatalog = directory.appendingPathComponent(harmonyPath)
            #expect(FileManager.default.fileExists(atPath: androidCatalog.path),
                    Comment(rawValue: "Android catalog must exist in \(fixture.name)"))
            #expect(FileManager.default.fileExists(atPath: harmonyCatalog.path),
                    Comment(rawValue: "HarmonyOS catalog must exist in \(fixture.name)"))
            let entries = try StringResourceLoader.load(android: androidCatalog.path, harmony: harmonyCatalog.path)
            for (sourceKey, nativeName) in androidKeys {
                #expect(entries[nativeName] != nil,
                        Comment(rawValue: "\(fixture.name) must declare \(sourceKey) in both base catalogs"))
            }
            #expect(entries.count == androidKeys.count || fixture.name == "v0-reject-missing-resource",
                    Comment(rawValue: "Catalogs must not silently add unregistered resources in \(fixture.name)"))
        }
    }

    @Test
    func literalTextRemainsAnExecutableContractCase() throws {
        let fixture = try #require(CorpusLoader.load(repository: GoldenTests.repository).first {
            $0.name == "v0-literal-text"
        })
        #expect(fixture.status == .ready)
        let result = try GoldenRunner.generate(fixture)
        #expect(GoldenRunner.differences(for: fixture, result: result) == [])
    }
}
